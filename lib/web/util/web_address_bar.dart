/// 주소창(브라우저 URL) 조작 파사드.
///
/// 스라 웹은 해시 라우팅 SPA라, 카카오/페북 크롤러가 주소창의 생 해시 URL을 읽어도
/// (`#` 뒤는 서버로 전송 안 됨) index.html의 사이트 공통 OG(홈)만 본다. 그래서
/// **브라우저 기본 공유 버튼**으로 공유하면 콘텐츠가 아니라 홈 미리보기가 떠버린다.
///
/// 해결: 공유 가능한 콘텐츠 페이지(이벤트·커뮤니티·크루·라이브톡·프로필·중고거래)에
/// 들어오면 주소창을 크롤러가 읽는 `/share/...` 링크로 `history.replaceState`(같은
/// 오리진이라 허용) 한다. 그러면 기본 공유도 이 링크를 넘겨 → 백엔드가 OG 서빙 →
/// 정상 미리보기. 사람은 그 링크를 클릭하면 백엔드가 실제 페이지로 302 리다이렉트한다.
///
/// 실제 구현은 `package:web`을 써서 **웹 타깃에서만 컴파일**되고, 그 외(테스트·모바일)는
/// 아무 일도 안 하는 스텁이다.
export 'web_address_bar_stub.dart'
    if (dart.library.js_interop) 'web_address_bar_web.dart';
